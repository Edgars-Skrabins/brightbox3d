    struct EditorTextInfo
    {
        const char* key;
        const char* english;
        int argumentCount;
    };

    const EditorTextInfo& GetTextInfo(EditorText text);

    class EditorTextTable
    {
    public:
        static EditorTextTable& Get();

        const std::string& Lookup(EditorText text) const { return m_texts[static_cast<size_t>(text)]; }
        bool LoadOverrides(const std::filesystem::path& path, std::string& error);
        void Reset();

    private:
        EditorTextTable();

        std::array<std::string, static_cast<size_t>(EditorText::Count)> m_texts;
    };

    inline const char* Text(EditorText text)
    {
        return EditorTextTable::Get().Lookup(text).c_str();
    }

    template <typename... Args>
    std::string Text(EditorText text, const Args&... arguments)
    {
        BrightAssert(GetTextInfo(text).argumentCount == static_cast<int>(sizeof...(Args)), "EditorText used with the wrong number of arguments");
        return std::vformat(EditorTextTable::Get().Lookup(text), std::make_format_args(arguments...));
    }
